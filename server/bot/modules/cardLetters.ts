/** A letter's rows as bits, the leftmost dot the highest, or null for one the font does not draw. */
const kept = new Map<string, readonly number[]>();
export function letterRows(letter: string): readonly number[] | null {
  const drawn = LETTERS[letter];
  if (drawn === undefined) return null;
  let rows = kept.get(letter);
  if (!rows) {
    rows = drawn.split(' ').map((row) => [...row].reduce((bits, dot) => (bits << 1) | (dot === '#' ? 1 : 0), 0));
    kept.set(letter, rows);
  }
  return rows;
}

/** Only the letters the font draws, so a name in another script never leaves a gap. */
export const drawable = (text: string): string =>
  [...text]
    .filter((letter) => letterRows(letter) !== null)
    .join('')
    .replace(/\s+/g, ' ')
    .trim();

/** How wide words are at `scale` (dots of this many pixels), in pixels. */
export const wordsWide = (text: string, scale: number): number =>
  Math.max(0, [...text].length * (LETTER_WIDE + LETTER_GAP) - LETTER_GAP) * scale;
