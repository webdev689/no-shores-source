/** A record's size in texels and its frames (an animated record has more than one). */
export interface PictureSize {
  readonly width: number;
  readonly height: number;
  readonly frames: number;
}

const parsed = new Map<number, readonly PictureSize[]>();

/** An archive's records, or null for an archive the catalog does not hold. */
export function catalogRecords(archive: number): readonly PictureSize[] | null {
  const kept = parsed.get(archive);
  if (kept) return kept;
  const text = CATALOG[archive];
  if (text === undefined) return null;
  const records: PictureSize[] = [];
  for (const part of text.split(' ')) {
    const match = /^(\d+)x(\d+)(?:f(\d+))?(?:\*(\d+))?$/.exec(part);
    if (!match) throw new Error(`textures catalog: bad entry '${part}' in archive ${archive}`);
    for (let k = 0; k < Number(match[4] ?? 1); k++)
      records.push({ width: Number(match[1]), height: Number(match[2]), frames: Number(match[3] ?? 1) });
  }
  parsed.set(archive, records);
  return records;
}

/** Every archive the catalog holds, in order. */
export const catalogArchives = (): number[] => Object.keys(CATALOG).map(Number);

/** A record's size and frames, or null for a record the catalog does not hold. */
export function pictureSize(archive: number, record: number): PictureSize | null {
  return catalogRecords(archive)?.[record] ?? null;
}
